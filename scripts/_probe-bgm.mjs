// 배경 음악 확인 — 첫 탭 뒤 사냥터 곡 · 대장간 곡 · 사운드 끄면 멈춤
import { launchBrowser } from "./launch-browser.mjs";
const BASE = "http://localhost:5173", H = "mock-local-dev", now = Date.now();
const browser = await launchBrowser({ args: ["--no-sandbox", "--autoplay-policy=no-user-gesture-required"] }); const page = await browser.newPage(); const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
await page.setViewport({ width: 390, height: 844, deviceScaleFactor: 1, isMobile: true, hasTouch: true });
await page.goto(BASE, { waitUntil: "networkidle0" });
await page.evaluate((s) => { localStorage.clear(); for (const [k, v] of Object.entries(s)) localStorage.setItem(k, v); }, { [`dodgebullets:progression:v1:${H}`]: JSON.stringify({ version: 5, level: 20, redGems: 100, idleClaimedAt: now, updatedAt: now, onboardingStep: 4, sessionCount: 9, partyIds: ["mia"], partyCap: 4, claimedRewards: ["dodge-tutorial"], pioneeredArea: 3, discoverySeeded: true, discovered: [] }), [`dodgebullets:titans:${H}`]: JSON.stringify({ gold: 1000, stage: 2, bestStage: 2, heroes: { mia: 5 }, lastActiveAt: now }), [`dodgebullets:attendance:v1:${H}`]: JSON.stringify({ lastClaimDate: new Date().toLocaleDateString("sv-SE"), totalDays: 3, consecutiveDays: 3 }), "dodge-bullets:soundEnabled": "1" });
await page.reload({ waitUntil: "networkidle0" }); await sleep(1200);
const st = () => page.evaluate(() => window.__bgm?.());
const out = [];
out.push(["before tap", await st()]);
await page.mouse.click(200, 400); await sleep(1500);
out.push(["after tap (hunt)", await st()]);
const clickText = (sel, text) => page.evaluate(({ sel, text }) => { const el = [...document.querySelectorAll(sel)].find((b) => b.textContent.trim().includes(text)); el?.click(); return !!el; }, { sel, text });
await page.evaluate(() => { for (let k = 0; k < 5; k += 1) { const c = document.querySelector(".idle-claim"); if (c) { c.click(); continue; } const b = [...document.querySelectorAll("button")].filter((x) => !x.closest(".titans-bottom-nav")).find((x) => /^(닫기|확인|나중에)$/.test(x.textContent.trim())); if (b) b.click(); } });
await clickText(".titans-bottom-nav button", "모험"); await sleep(500);
await clickText(".nav-popup-grid button", "대장간"); await sleep(2000);
out.push(["forge", await st()]);
await page.goBack().catch(() => {});
await page.goto(BASE, { waitUntil: "networkidle0" }); await sleep(1000);
await page.mouse.click(200, 400); await sleep(800);
await clickText(".titans-bottom-nav button", "모험"); await sleep(500);
await clickText(".nav-popup-grid button", "비트 수련"); await sleep(2000);
out.push(["beat (off)", await st()]);
await page.evaluate(() => { localStorage.setItem("dodge-bullets:soundEnabled", "0"); window.dispatchEvent(new Event("dodge-sound-change")); });
await sleep(800);
out.push(["sound off", await st()]);
console.log(out.map(([k, v]) => k.padEnd(18) + JSON.stringify(v)).join("\n"));
await browser.close();
